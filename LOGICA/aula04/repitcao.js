// Declarar uma variável chamada contador que recebe um valor numérico
let contador = 0

// Enquanto o contador for menor do que 10 repita
while (contador <= 10) {
    console.log("OLHA A HORA DO CAFÉ!")
    console.log("VENHA TOMAR SEU CAFÉ!")
    console.log("CAFÉ DA MANHÃ, CAFÉ DA TARDE! NÃO IMPORTA!")
    console.log("VENHA TOMAR O SEU CEFÉ!!!")

    // Adicionar ++ após o nome de uma variavel faz com que seja adicionado 1 ao seu valor
    contador++
    console.log(contador);

}