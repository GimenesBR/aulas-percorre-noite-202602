// Era uma vez os laços de repetição da logica de programação e o Laço  for era o mais utilizado por economizar espaço e trazer para sempre. fim.

// Para utilizar o for é necessario ter um contador para que delimitamos a quantidade de vezes que algo será repetido. A estrutura do for recebe inicialização, condição e incremento.

console.log("Vou contar até 10 e depois dizer morango");

//  inicialização
for (let i = 2;  i <= 10;  i +=2  ) {
    console.log(i);
}

